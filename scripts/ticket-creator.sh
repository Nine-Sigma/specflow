create_and_plan() {
    # Full orchestration: spec -> epic -> stories -> mapping -> plan
    # Arguments: feature_name
    # Returns: summary of what was created
    local feature="$1"

    # Step 1: Verify spec exists
    if ! _spec_exists "$feature"; then
        echo "Error: Spec not found: $SPECS_DIR/$feature/spec.md" >&2
        return 1
    fi

    # Step 2: Check for approval (optional but noted)
    local approval_file="$SPECS_DIR/$feature/approval.md"
    if [ -f "$approval_file" ]; then
        echo "  Found approval: $approval_file"
    else
        echo "  Note: No approval file found (continuing anyway)"
    fi

    # Step 3: Create epic
    echo "Creating epic..."
    local epic_json
    epic_json=$(create_epic_from_spec "$feature")
    if [ $? -ne 0 ]; then
        echo "Error: Failed to create epic" >&2
        return 1
    fi
    local epic_number
    epic_number=$(echo "$epic_json" | jq -r '.number')
    echo "  Created epic #$epic_number"

    # Step 4: Create stories
    echo "Creating stories..."
    local stories_json
    stories_json=$(create_stories_from_spec "$feature" "$epic_json")
    if [ $? -ne 0 ]; then
        echo "Error: Failed to create stories" >&2
        return 1
    fi
    local story_count
    story_count=$(echo "$stories_json" | jq 'length')
    echo "  Created $story_count stories"

    # Step 5: Generate plan via plan-generator.sh
    if [ -f "$SCRIPT_DIR/plan-generator.sh" ]; then
        echo ""
        echo "Generating execution plan..."
        "$SCRIPT_DIR/plan-generator.sh" generate "$feature" "$epic_json" "$stories_json"
    else
        echo "Warning: plan-generator.sh not found, skipping plan generation" >&2
    fi

    # Step 6: Return summary
    local summary
    summary=$(jq -n \
        --arg feature "$feature" \
        --argjson epic "$epic_json" \
        --argjson stories "$stories_json" \
        --argjson story_count "$story_count" \
        '{
            feature: $feature,
            epic: $epic,
            stories: $stories,
            total_tickets: ($story_count + 1)
        }')

    echo ""
    echo "=========================================="
    echo "COMPLETE: Created $((story_count + 1)) tickets for $feature"
    echo "  Epic: #$epic_number"
    echo "  Stories: $story_count"
    if [ -f "$TICKETS_DIR/${feature}.json" ]; then
        echo "  Mapping: $TICKETS_DIR/${feature}.json"
    fi
    if [ -f "$SPECS_DIR/$feature/PLAN.md" ]; then
        echo "  Plan: $SPECS_DIR/$feature/PLAN.md"
    fi
    echo "=========================================="

    _log_creation "$feature" "Complete: epic=#$epic_number, stories=$story_count"

    # Return success
    return 0
}

# =============================================================================
# Preview Functions
# =============================================================================

preview_tickets() {
    # Show what would be created without creating
    local feature="$1"

    if ! _spec_exists "$feature"; then
        echo "Error: Spec not found: $SPECS_DIR/$feature/spec.md" >&2
        return 1
    fi

    local spec_content
    spec_content=$(_read_spec "$feature")

    echo "=========================================="
    echo "TICKET PREVIEW: $feature"
    echo "=========================================="
    echo ""

    # Epic preview
    local epic_body
    epic_body=$(build_epic_body "$feature")
    local pillar_labels
    pillar_labels=$(extract_pillar_labels "$spec_content")

    echo "EPIC:"
    echo "  Title: Epic: $feature"
    echo "  Labels: specflow:epic,$pillar_labels"
    echo "  Body preview (first 500 chars):"
    echo "  ----------------------------------------"
    echo "${epic_body:0:500}..."
    echo "  ----------------------------------------"
    echo ""

    # Stories preview
    local stories
    stories=$(determine_stories "$spec_content" "$feature")
    local story_count
    story_count=$(echo "$stories" | jq 'length')

    echo "STORIES ($story_count):"
    for i in $(seq 0 $((story_count - 1))); do
        local title story_points story_type
        title=$(echo "$stories" | jq -r ".[$i].title")
        story_points=$(echo "$stories" | jq -r ".[$i].story_points")
        story_type=$(echo "$stories" | jq -r ".[$i].type")

        echo "  $((i + 1)). $title"
        echo "     Type: $story_type"
        echo "     Story Points: $story_points"
    done
    echo ""

    # Wave grouping preview
    echo "WAVE GROUPING (preliminary):"
    echo "  Wave 1 (independent): Backend, Infrastructure"
    echo "  Wave 2 (dependent): Frontend, Testing"
    echo ""

    echo "=========================================="
    echo "Use 'ticket-creator.sh $feature --yes' to create"
    echo "=========================================="
}

# =============================================================================
# CLI Interface
# =============================================================================

show_help() {
    echo "Ticket Creator - Create tickets from approved specs"
    echo ""
    echo "Usage:"
    echo "  ticket-creator.sh <feature>           Create tickets with confirmation"
    echo "  ticket-creator.sh <feature> --yes     Create tickets without confirmation"
    echo "  ticket-creator.sh preview <feature>   Preview without creating"
    echo "  ticket-creator.sh create <feature>    Same as <feature>"
    echo "  ticket-creator.sh --help              Show this help"
    echo ""
    echo "The script reads specs from .specflow/specs/{feature}/spec.md"
    echo "and creates an epic + stories in the configured tracker."
    echo ""
    echo "Examples:"
    echo "  ticket-creator.sh add-logout-button"
    echo "  ticket-creator.sh preview payment-integration"
    echo "  ticket-creator.sh payment-integration --yes"
}

main() {
    local command="${1:-}"
    local feature=""
    local auto_confirm=false

    # Parse arguments
    case "$command" in
        --help|-h)
            show_help
            exit 0
            ;;
        preview)
            feature="${2:-}"
            if [ -z "$feature" ]; then
                echo "Error: Feature name required" >&2
                show_help
                exit 1
            fi
            preview_tickets "$feature"
            exit 0
            ;;
        create)
            feature="${2:-}"
            shift 2 || true
            ;;
        "")
            echo "Error: Feature name required" >&2
            show_help
            exit 1
            ;;
        *)
            feature="$command"
            shift || true
            ;;
    esac

    # Check for --yes flag
    for arg in "$@"; do
        if [ "$arg" = "--yes" ] || [ "$arg" = "-y" ]; then
            auto_confirm=true
        fi
    done

    if [ -z "$feature" ]; then
        echo "Error: Feature name required" >&2
        show_help
        exit 1
    fi

    # Check spec exists
    if ! _spec_exists "$feature"; then
        echo "Error: Spec not found: $SPECS_DIR/$feature/spec.md" >&2
        exit 1
    fi

    # Show preview
    preview_tickets "$feature"
    echo ""

    # Confirm unless --yes
    if [ "$auto_confirm" = false ]; then
        read -rp "Create these tickets? [y/N] " confirm
        if [[ ! "$confirm" =~ ^[Yy]$ ]]; then
            echo "Aborted."
            exit 0
        fi
    fi

    echo ""
    echo "Creating tickets..."
    echo ""

    # Use integrated create_and_plan function
    create_and_plan "$feature"
}

# Run main if executed directly
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    main "$@"
fi
